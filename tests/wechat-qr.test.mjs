for (const fixture of fixtures) {
  test(`byte-mode L mask-0 golden matrix, version ${fixture.version}`, () => {
    const matrix = qrMatrix(fixture.text);
    assert.equal(matrix.length, 17 + 4 * fixture.version);
    assert.ok(matrix.every(row => row.every(value => value === 0 || value === 1)));
    assert.deepEqual(
      matrix.map(row => row.join('')),
      fixture.rows,
    );
  });
}

test('finder cores, timing patterns, and dark module', () => {
  const { text, version } = fixtures[1];
  const matrix = qrMatrix(text);
  const size = 17 + 4 * version;
  const finder = ['1111111', '1000001', '1011101', '1011101', '1011101', '1000001', '1111111'];
  for (const [top, left] of [
    [0, 0],
    [0, size - 7],
    [size - 7, 0],
  ]) {
    assert.deepEqual(
      matrix.slice(top, top + 7).map(row => row.slice(left, left + 7).join('')),
      finder,
    );
  }
  assert.equal(matrix[4 * version + 9][8], 1);
  for (let index = 8; index < size - 8; index++) {
    assert.equal(matrix[6][index], Number(index % 2 === 0));
    assert.equal(matrix[index][6], Number(index % 2 === 0));
  }
});

test('capacity selection counts UTF-8 bytes and rejects overflow', () => {
  assert.equal(qrMatrix('').length, 21);
  assert.equal(qrMatrix('x'.repeat(17)).length, 21);
  assert.equal(qrMatrix('x'.repeat(18)).length, 25);
  assert.equal(qrMatrix('\u00e9'.repeat(9)).length, 25);
  assert.equal(qrMatrix('x'.repeat(230)).length, 53);
  assert.equal(qrMatrix('x'.repeat(231)).length, 57);
  assert.equal(qrMatrix('x'.repeat(2953)).length, 177);
  assert.throws(() => qrMatrix('x'.repeat(2954)), Error);
  assert.throws(() => qrMatrix('x'.repeat(3000)), Error);
  assert.throws(() => qrMatrix('\u00e9'.repeat(1477)), Error);
});

test('terminal rendering preserves modules, quiet zone, colors, and final newline', () => {
  const matrix = qrMatrix('hello');
  const rendered = renderQr(matrix);
  assert.ok(rendered.endsWith('\n'));
  assert.ok(!rendered.endsWith('\n\n'));
  const lines = rendered.slice(0, -1).split('\n');
  assert.equal(lines.length, Math.ceil((matrix.length + 8) / 2));
  const pixels = { ' ': [0, 0], '\u2580': [1, 0], '\u2584': [0, 1], '\u2588': [1, 1] };
  for (const [index, line] of lines.entries()) {
    assert.ok(line.startsWith('\x1b[30;107m'));
    assert.ok(line.endsWith('\x1b[0m'));
    const content = line.slice('\x1b[30;107m'.length, -'\x1b[0m'.length);
    assert.equal(content.length, matrix.length + 8);
    assert.match(content, /^[\u2588\u2580\u2584 ]+$/u);
    if (index < 2 || index >= lines.length - 2) assert.match(content, /^ +$/);
    for (const [column, character] of [...content].entries()) {
      for (const half of [0, 1]) {
        assert.equal(pixels[character][half], matrix[index * 2 + half - 4]?.[column - 4] ?? 0);
      }
    }
  }
});
